// Fetches the Material Symbols glyphs FleetHub uses and writes
// src/assets/icon-font.css with the subset inlined as a data: URI.
//
// Inlined for the same reason as the text faces: the single-file preview's host
// blocks external requests, and an icon font that fails to load does not fall
// back to anything — it renders its ligature names as words.
//
// The `icon_names` parameter returns only the glyphs asked for, which is the
// difference between 7 kB and the 3.5 MB of the whole variable font. It also
// pins the axes, so the weight below is fixed at build time rather than live.
//
// Re-run with `npm run build:icon-font` after changing ICONS.

import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/** Ligature names, in the order icons.tsx declares them. */
const ICONS = [
  'chevron_left',
  'chevron_right',
  'keyboard_arrow_down',
  'keyboard_arrow_up',
  'close',
  'check',
  'search',
  'tune',
  'my_location',
  'map',
  'local_shipping',
  'notifications',
  'person',
  'grid_view',
  'group',
  'description',
  'photo_camera',
  'bolt',
  'menu',
  'backspace',
  'refresh',
  'lock',
  'mail',
  'call',
  'send',
  'login',
  'dialpad',
  'edit',
  'save',
  'delete',
  'admin_panel_settings',
  'arrow_forward',
]

/** opsz, wght, FILL, GRAD — single values, since icon_names pins the axes. */
const AXES = '24,400,0,0'

const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36'

// The endpoint is picky: names sorted, no display parameter.
const names = [...ICONS].sort().join(',')
const cssUrl =
  'https://fonts.googleapis.com/css2?family=Material+Symbols+Sharp' +
  `:opsz,wght,FILL,GRAD@${AXES}&icon_names=${names}`

const res = await fetch(cssUrl, { headers: { 'User-Agent': UA } })
if (!res.ok) throw new Error(`Google Fonts said ${res.status} — is a name misspelt?`)
const css = await res.text()

const url = css.match(/url\((https:\/\/[^)]+)\)/)?.[1]
if (!url) throw new Error('no url() in the returned CSS — did the format change?')
const format = css.match(/format\('([^']+)'\)/)?.[1] ?? 'truetype'
const mime = format === 'woff2' ? 'font/woff2' : 'font/ttf'

const bytes = Buffer.from(await (await fetch(url)).arrayBuffer())

const out = `/* GENERATED by scripts/build-icon-font.mjs — do not edit. Run \`npm run build:icon-font\`. */
@font-face {
  font-family: 'FleetHub Symbols';
  font-style: normal;
  font-weight: 400;
  /* block, not swap: the fallback for an icon font is its ligature spelt out. */
  font-display: block;
  src: url(data:${mime};base64,${bytes.toString('base64')}) format('${format}');
}

.fh-icon {
  font-family: 'FleetHub Symbols';
  font-weight: normal;
  font-style: normal;
  line-height: 1;
  letter-spacing: normal;
  text-transform: none;
  display: inline-block;
  white-space: nowrap;
  word-wrap: normal;
  direction: ltr;
  flex: none;
  -webkit-font-feature-settings: 'liga';
  font-feature-settings: 'liga';
  font-variant-ligatures: common-ligatures;
  -webkit-font-smoothing: antialiased;
  user-select: none;
}
`

const target = fileURLToPath(new URL('../src/assets/icon-font.css', import.meta.url))
await writeFile(target, out)
console.log(
  `icon-font.css written — ${ICONS.length} glyphs, ${(bytes.length / 1024).toFixed(1)} kB ${format}`
)
